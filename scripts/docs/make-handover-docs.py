def shot(doc, caption):
    """ที่ว่างสำหรับวางภาพหน้าจอ พร้อมคำบรรยายว่าควรเป็นภาพอะไร"""
    t = doc.add_table(rows=2, cols=1)
    t.style = "Table Grid"
    top = t.rows[0].cells[0]
    top.text = ""
    p = top.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    thai_font(p.add_run("\n[ ภาพหน้าจอ ]\n"), size=9, color=MUTED)
    shade(top, "F2F2F2")
    bottom = t.rows[1].cells[0]
    bottom.text = ""
    p = bottom.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    thai_font(p.add_run(caption), size=9, color=MUTED)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


def step(doc, n, action, see):
    """หนึ่งขั้นตอน: ทำอะไร แล้วจะเห็นอะไร"""
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(1)
    thai_font(p.add_run("ขั้นที่ %d  " % n), size=10.5, bold=True, color=ACCENT)
    thai_font(p.add_run(action), size=10.5, bold=True)
    p2 = doc.add_paragraph()
    p2.paragraph_format.left_indent = Cm(1.6)
    p2.paragraph_format.space_after = Pt(8)
    thai_font(p2.add_run("จะเห็น: " + see), size=10, color=MUTED)
    return p


