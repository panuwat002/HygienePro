def thai_font(run, size=None, bold=None, color=None):
    run.font.name = FONT
    if size:
        run.font.size = Pt(size)
    if bold is not None:
        run.font.bold = bold
    if color is not None:
        run.font.color.rgb = color
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rpr.append(rfonts)
    for attr in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
        rfonts.set(qn(attr), FONT)
    return run


def base_styles(doc):
    for name in ("Normal", "List Bullet", "List Number", "Title",
                 "Heading 1", "Heading 2", "Heading 3"):
        try:
            st = doc.styles[name]
        except KeyError:
            continue
        st.font.name = FONT
        rpr = st.element.get_or_add_rPr()
        rfonts = rpr.find(qn("w:rFonts"))
        if rfonts is None:
            rfonts = OxmlElement("w:rFonts")
            rpr.append(rfonts)
        for attr in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
            rfonts.set(qn(attr), FONT)
    doc.styles["Normal"].font.size = Pt(10.5)


def h(doc, text, level=1):
    p = doc.add_heading("", level=level)
    thai_font(p.add_run(text),
              size={0: 20, 1: 15, 2: 12.5, 3: 11}.get(level, 11),
              bold=True, color=ACCENT)
    return p


def para(doc, text, size=10.5, bold=False, color=None, space_after=6, align=None):
    p = doc.add_paragraph()
    thai_font(p.add_run(text), size=size, bold=bold, color=color)
    p.paragraph_format.space_after = Pt(space_after)
    if align:
        p.alignment = align
    return p


def bullet(doc, text, size=10.5, level=0):
    p = doc.add_paragraph(style="List Bullet")
    thai_font(p.add_run(text), size=size)
    p.paragraph_format.space_after = Pt(3)
    p.paragraph_format.left_indent = Cm(0.8 + 0.6 * level)
    return p


def numbered(doc, text, size=10.5):
    p = doc.add_paragraph(style="List Number")
    thai_font(p.add_run(text), size=size)
    p.paragraph_format.space_after = Pt(3)
    return p


def shade(cell, hexcolor):
    tcpr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:fill"), hexcolor)
    tcpr.append(shd)


def table(doc, headers, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.LEFT
    for i, head in enumerate(headers):
        cell = t.rows[0].cells[i]
        cell.text = ""
        thai_font(cell.paragraphs[0].add_run(head), size=9.5, bold=True)
        shade(cell, "DCE6F1")
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ""
            thai_font(cells[i].paragraphs[0].add_run(str(val)), size=9.5)
    if widths:
        for r in t.rows:
            for i, w in enumerate(widths):
                r.cells[i].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


def note(doc, text, fill="FFF4CE"):
    t = doc.add_table(rows=1, cols=1)
    t.style = "Table Grid"
    cell = t.rows[0].cells[0]
    cell.text = ""
    thai_font(cell.paragraphs[0].add_run(text), size=9.5)
    shade(cell, fill)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


def cover(doc, title, subtitle, meta_rows):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    thai_font(p.add_run("HygienePro"), size=26, bold=True, color=ACCENT)
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    thai_font(p.add_run("ระบบตรวจสอบสุขลักษณะการผลิต"), size=12, color=MUTED)
    doc.add_paragraph()
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    thai_font(p.add_run(title), size=20, bold=True)
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    thai_font(p.add_run(subtitle), size=11, color=MUTED)
    doc.add_paragraph()
    doc.add_paragraph()
    table(doc, ["รายการ", "รายละเอียด"], meta_rows, widths=[5, 11])
    doc.add_page_break()


def footer_note(doc, text):
    p = doc.sections[0].footer.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    thai_font(p.add_run(text), size=8, color=MUTED)


def signatures(doc, left, right):
    doc.add_paragraph()
    t = doc.add_table(rows=1, cols=2)
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for cell, role in zip(t.rows[0].cells, (left, right)):
        cell.text = ""
        for line in ("", "ลงชื่อ ____________________________", role,
                     "วันที่ ____________________________"):
            p = cell.add_paragraph()
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            thai_font(p.add_run(line), size=10)
    return t


